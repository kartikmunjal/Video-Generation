#!/usr/bin/env python3
"""Generate the augmentation-study report and hashed evidence manifest."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def pp(metric: dict) -> str:
    lo, hi = metric["ci95"]
    return f"{100 * metric['estimate']:.3f} pp [{100 * lo:.3f}, {100 * hi:.3f}]"


def number(metric: dict) -> str:
    lo, hi = metric["ci95"]
    return f"{metric['estimate']:.3f} [{lo:.3f}, {hi:.3f}]"


def pvalue(value: float, replicates: int) -> str:
    return f"<{1 / replicates:.4g}" if value == 0 else f"{value:.4g}"


def update_readme(path: Path, block: str) -> None:
    begin = "<!-- BEGIN GENERATED CONFIRMATORY RESULTS -->"
    end = "<!-- END GENERATED CONFIRMATORY RESULTS -->"
    text = path.read_text(encoding="utf-8")
    if text.count(begin) != 1 or text.count(end) != 1:
        raise SystemExit("README generated-result markers are missing or duplicated")
    prefix, remainder = text.split(begin)
    _, suffix = remainder.split(end)
    path.write_text(f"{prefix}{begin}\n{block.rstrip()}\n{end}{suffix}", encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--analysis", type=Path, required=True)
    parser.add_argument("--selections", type=Path, required=True)
    parser.add_argument("--run-metrics", type=Path, required=True)
    parser.add_argument("--predictions", type=Path, required=True)
    parser.add_argument("--features", type=Path, required=True)
    parser.add_argument("--preregistration", type=Path, required=True)
    parser.add_argument("--implementation-note", type=Path, action="append", required=True)
    parser.add_argument("--environment", type=Path, required=True)
    parser.add_argument("--readme", type=Path)
    parser.add_argument("--output-dir", type=Path, required=True)
    args = parser.parse_args()
    result = json.loads(args.analysis.read_text())
    macro = result["primary"]["guided_minus_random_macro_recall"]
    worst = result["primary"]["guided_minus_random_worst_decile_recall"]
    rejection = result["quality_rejection_rate"]
    mechanism = result["mechanism"]["spearman_reward_gap_vs_error_delta"]
    selection_rows = sum(1 for line in args.selections.open() if line.strip())
    prediction_sets: dict[tuple, set[int]] = {}
    with args.predictions.open(encoding="utf-8") as handle:
        for line in handle:
            if not line.strip():
                continue
            row = json.loads(line)
            key = (row["official_split"], row["arm"], row["relative_path"])
            prediction_sets.setdefault(key, set()).add(int(row["prediction"]))
    seed_varying_predictions = sum(len(values) > 1 for values in prediction_sets.values())

    supported = macro["ci95"][0] > 0 and macro["p_holm"] < 0.05
    conclusion = (
        "Reward guidance improved macro recall over random augmentation under the frozen "
        "budget." if supported else
        "The study did not establish that reward guidance improves macro recall over random "
        "augmentation under the frozen budget."
    )
    lines = [
        "# Confirmatory report: reward-guided video augmentation",
        "",
        "This report is generated by `scripts/publish_confirmatory_report.py` from raw "
        "selection, prediction, and run artifacts; displayed values are not hand edited.",
        "",
        "## Design",
        "",
        f"The experiment selected one augmentation for each of {selection_rows:,} training "
        "sources across three official UCF-101 splits. Four arms used identical unique "
        "sources, example counts, feature extractor, classifier settings, and optimization "
        "seeds. The untouched official test sets contain no selection inputs.",
        "",
        f"Uncertainty uses {result['bootstrap_replicates']:,} deterministic paired "
        f"hierarchical-bootstrap replicates (`N_trials={result['n_trials']}`, "
        f"`N_optimization_seeds={result['n_optimization_seeds']}`). Holm adjustment covers "
        "the two confirmatory downstream outcomes.",
        "",
        f"The parent-matched `lbfgs` classifier is deterministic: {seed_varying_predictions:,} "
        "split×arm×video predictions varied across the three requested seed labels. The "
        "seed runs are reproducibility repeats, not independent trials; inferential "
        "replication comes from the three official splits.",
        "",
        "## Confirmatory outcomes",
        "",
        f"- Guided minus random macro recall: **{pp(macro)}**, Holm-adjusted "
        f"`p={pvalue(macro['p_holm'], result['bootstrap_replicates'])}`.",
        f"- Guided minus random worst-decile recall: **{pp(worst)}**, Holm-adjusted "
        f"`p={pvalue(worst['p_holm'], result['bootstrap_replicates'])}`.",
        f"- Guided rejection-to-clean-duplicate rate: **{100 * rejection['estimate']:.2f}% "
        f"[{100 * rejection['ci95'][0]:.2f}%, {100 * rejection['ci95'][1]:.2f}%]**.",
        "",
        conclusion,
        "",
        "## Selection mechanics",
        "",
        "| Arm | Selection counts |",
        "|---|---|",
    ]
    for arm, counts in result["selection_frequency"].items():
        rendered = ", ".join(f"`{name}`={count:,}" for name, count in counts.items())
        lines.append(f"| `{arm}` | {rendered} |")
    lines += [
        "",
        f"Across {result['mechanism']['n_split_class_cells']} split-by-class cells, the "
        "association between the guided-minus-random predicted-damage gap and downstream "
        f"error change was Spearman **{number(mechanism)}**. This is a mechanism check, not "
        "a causal estimate beyond the randomized policy comparison.",
        "",
        "## Evidence boundary",
        "",
        "The parent reward model was validated on controlled synthetic interventions and "
        "showed a retained leave-family-out temporal failure. This downstream study tests a "
        "fixed mild candidate set; it does not validate human preference, text-to-video "
        "generation, DiffusionDPO, or unrestricted reward optimization.",
        "",
        "The first execution stopped before producing a selection because H.264 macroblock "
        "padding made the pixel-MSE diagnostic grids unequal. The linked implementation note "
        "records the pre-outcome implementation corrections.",
        "",
        "## Reproduction",
        "",
        "The adjacent manifest records byte counts and SHA-256 hashes for every report input.",
        "",
    ]
    args.output_dir.mkdir(parents=True, exist_ok=True)
    report = args.output_dir / "REPORT.md"
    report.write_text("\n".join(lines), encoding="utf-8")
    if args.readme:
        frequency_rows = []
        for arm, counts in result["selection_frequency"].items():
            rendered = ", ".join(
                f"`{name}`={count:,}" for name, count in counts.items()
            )
            frequency_rows.append(f"| `{arm}` | {rendered} |")
        run_rows = []
        for arm, summary in result["run_summary"].items():
            run_rows.append(
                f"| `{arm}` | {summary['train_examples']:,} | "
                f"{summary['optimizer_iterations_min']}–{summary['optimizer_iterations_max']} | "
                f"{summary['fit_seconds_mean']:.3f} s |"
            )
        readme_block = f"""## Confirmatory results

The study evaluated **{selection_rows:,} training sources**, **{selection_rows * 4:,}
candidate augmentations**, four equal-example arms, **`N_trials=3` official
splits**, three deterministic reproducibility repeats, and **2,000 paired
hierarchical-bootstrap replicates**. The classifier produced
**{result['test_predictions_per_arm']:,} test predictions per arm** across the
three seed labels; **{seed_varying_predictions:,} split × arm × video predictions**
varied across seeds.

### Guided minus random

- Macro recall: **{pp(macro)}**, Holm-adjusted
  **p={pvalue(macro['p_holm'], result['bootstrap_replicates'])}**.
- Worst-decile recall: **{pp(worst)}**, Holm-adjusted
  **p={pvalue(worst['p_holm'], result['bootstrap_replicates'])}**.
- Guided rejection to a clean duplicate: **{100 * rejection['estimate']:.2f}%
  [{100 * rejection['ci95'][0]:.2f}%, {100 * rejection['ci95'][1]:.2f}%]**.
- Mechanism association across **{result['mechanism']['n_split_class_cells']}
  split × class cells**: Spearman rho **{number(mechanism)}**.

Both downstream confidence intervals cross zero, Holm-adjusted tests do not
reject the null, and the mechanism interval crosses zero. The confirmatory
study therefore did not establish that reward guidance improves recognition
over random augmentation under this budget.

### Selected augmentation counts

| Arm | Counts |
|---|---|
{chr(10).join(frequency_rows)}

### Equal-budget classifier execution

| Arm | Training examples | Realized iterations | Mean fit time |
|---|---:|---:|---:|
{chr(10).join(run_rows)}

The parent-matched `lbfgs` solver is deterministic, so the seed-labelled runs
are reproducibility repeats rather than independent trials. Inferential
replication comes from the three official dataset splits.
"""
        update_readme(args.readme, readme_block)
    inputs = [args.analysis, args.selections, args.run_metrics, args.predictions,
              args.features, args.preregistration, *args.implementation_note,
              args.environment]
    manifest = {
        "schema_version": 1,
        "study_id": result["study_id"],
        "generated_by": "scripts/publish_confirmatory_report.py",
        "artifacts": [
            {"path": str(path), "bytes": path.stat().st_size, "sha256": sha256(path)}
            for path in inputs
        ],
        "report": {"path": str(report), "bytes": report.stat().st_size,
                   "sha256": sha256(report)},
    }
    if args.readme:
        manifest["readme"] = {"path": str(args.readme), "bytes": args.readme.stat().st_size,
                              "sha256": sha256(args.readme)}
    (args.output_dir / "artifact_manifest.json").write_text(
        json.dumps(manifest, indent=2) + "\n", encoding="utf-8"
    )
    print(report)


if __name__ == "__main__":
    main()
